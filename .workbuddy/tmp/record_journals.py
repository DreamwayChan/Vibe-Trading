def main() -> None:
    journal = DecisionJournal()
    ok, blocked = 0, 0
    for entry in ENTRIES:
        signal = journal.record(
            run_id=entry["run_id"],
            thesis=entry["thesis"],
            invalidation=entry["invalidation"],
            planned_position=entry["planned_position"],
            planned_risk=entry["planned_risk"],
            symbol="",
            strict=False,
        )
        status = "tradable" if signal.tradable else f"BLOCKED {signal.block_reasons}"
        print(f"{signal.signal_id}  {entry['run_id'][:44]:<44}  {status}")
        ok += 1 if signal.tradable else 0
        blocked += 0 if signal.tradable else 1
    print(f"\nwritten={len(ENTRIES)} tradable={ok} blocked={blocked}")
    print(f"journal_path={journal.path}")


if __name__ == "__main__":
    main()
